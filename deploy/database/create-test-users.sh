#!/usr/bin/env bash
# create-test-users.sh — Phase 3 test user provisioning via GoTrue admin API.
#
# Creates three test users (A, B, C) through the GoTrue admin API so the RLS
# isolation suite has real auth.users rows with real UUIDs. We NEVER INSERT
# into auth.users directly — that would bypass GoTrue's user management.
#
# Prerequisites:
#   - Phase 2 complete (stack running, GoTrue healthy)
#   - Phase 3 migrations applied (deploy/database/apply-migrations.sh)
#   - SERVICE_ROLE_KEY set (from deploy/env/.env)
#   - SUPABASE_PUBLIC_URL or PROXY_DOMAIN set
#
# Usage:
#   bash deploy/database/create-test-users.sh
#
# Output: exports LUMO_TEST_USER_A, LUMO_TEST_USER_B, LUMO_TEST_USER_C
#         and writes them to /tmp/lumo-test-users.env for the security runner.
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
ENV_FILE="$ROOT/deploy/env/.env"

# ---- load env ---------------------------------------------------------------
if [ -f "$ENV_FILE" ]; then
  SERVICE_ROLE_KEY="$(grep -E '^SERVICE_ROLE_KEY=' "$ENV_FILE" | cut -d= -f2-)"
  SUPABASE_PUBLIC_URL="$(grep -E '^SUPABASE_PUBLIC_URL=' "$ENV_FILE" | cut -d= -f2-)"
  export SERVICE_ROLE_KEY SUPABASE_PUBLIC_URL
fi

: "${SERVICE_ROLE_KEY:?SERVICE_ROLE_KEY must be set in deploy/env/.env}"
: "${SUPABASE_PUBLIC_URL:?SUPABASE_PUBLIC_URL must be set in deploy/env/.env}"

AUTH_URL="${SUPABASE_PUBLIC_URL}/auth/v1"
TEST_EMAIL_DOMAIN="lumo-test.local"
OUTPUT_FILE="/tmp/lumo-test-users.env"

# ---- check if curl is available ---------------------------------------------
if ! command -v curl >/dev/null 2>&1; then
  echo "FAIL: curl is required but not installed." >&2
  exit 1
fi

echo "== Phase 3: Creating test users via GoTrue admin API =="
echo "  auth URL: $AUTH_URL"
echo ""

# ---- helper: create or get user UUID ----------------------------------------
create_user() {
  local email="$1"
  local password="$2"

  # Try to create the user via admin API (-k for staging TLS)
  RESPONSE=$(curl -sk -w '\n%{http_code}' \
    -X POST "$AUTH_URL/admin/users" \
    -H "Authorization: Bearer $SERVICE_ROLE_KEY" \
    -H "apikey: $SERVICE_ROLE_KEY" \
    -H "Content-Type: application/json" \
    -d "{\"email\":\"$email\",\"password\":\"$password\",\"email_confirm\":true}" \
    2>/dev/null)

  HTTP_CODE=$(echo "$RESPONSE" | tail -1)
  BODY=$(echo "$RESPONSE" | sed '$d')

  if [ "$HTTP_CODE" = "200" ] || [ "$HTTP_CODE" = "201" ]; then
    # Extract UUID from response
    UUID=$(echo "$BODY" | python3 -c "import sys,json; print(json.load(sys.stdin).get('id',''))" 2>/dev/null || echo "")
    if [ -n "$UUID" ]; then
      echo "$UUID"
      return 0
    fi
  fi

  # If user already exists, try to get their UUID via admin list
  if [ "$HTTP_CODE" = "422" ]; then
    echo "  (user already exists, fetching UUID...)" >&2
    LIST_RESPONSE=$(curl -sk \
      "$AUTH_URL/admin/users" \
      -H "Authorization: Bearer $SERVICE_ROLE_KEY" \
      -H "apikey: $SERVICE_ROLE_KEY" \
      2>/dev/null)

    UUID=$(echo "$LIST_RESPONSE" | python3 -c "
import sys, json
data = json.load(sys.stdin)
users = data.get('users', data) if isinstance(data, dict) else data
for u in users:
    if u.get('email') == '$email':
        print(u.get('id', ''))
        break
" 2>/dev/null || echo "")

    if [ -n "$UUID" ]; then
      echo "$UUID"
      return 0
    fi
  fi

  echo "FAIL: could not create or find user $email (HTTP $HTTP_CODE)" >&2
  echo "  Response: $BODY" >&2
  return 1
}

# ---- create three test users ------------------------------------------------
EMAIL_A="user-a@$TEST_EMAIL_DOMAIN"
EMAIL_B="user-b@$TEST_EMAIL_DOMAIN"
EMAIL_C="user-c@$TEST_EMAIL_DOMAIN"

PASSWORD_A="LumoTest-A-2026!secure"
PASSWORD_B="LumoTest-B-2026!secure"
PASSWORD_C="LumoTest-C-2026!secure"

echo "  creating user A ($EMAIL_A)..."
USER_A=$(create_user "$EMAIL_A" "$PASSWORD_A")
echo "  OK: $USER_A"

echo "  creating user B ($EMAIL_B)..."
USER_B=$(create_user "$EMAIL_B" "$PASSWORD_B")
echo "  OK: $USER_B"

echo "  creating user C ($EMAIL_C)..."
USER_C=$(create_user "$EMAIL_C" "$PASSWORD_C")
echo "  OK: $USER_C"

# ---- write output file ------------------------------------------------------
cat > "$OUTPUT_FILE" << EOF
# Lumo Base test users — generated by deploy/database/create-test-users.sh
# This file is temporary and should be deleted after testing.
export LUMO_TEST_USER_A="$USER_A"
export LUMO_TEST_USER_B="$USER_B"
export LUMO_TEST_USER_C="$USER_C"
EOF

chmod 600 "$OUTPUT_FILE"

echo ""
echo "== test users created =="
echo "  User A: $USER_A ($EMAIL_A)"
echo "  User B: $USER_B ($EMAIL_B)"
echo "  User C: $USER_C ($EMAIL_C)"
echo ""
echo "  Output written to: $OUTPUT_FILE (mode 600)"
echo ""
echo "Next: source the file and run the security suite:"
echo "  source $OUTPUT_FILE"
echo "  LUMO_DB_URL='...' bash tests/security/run-security-tests.sh"
